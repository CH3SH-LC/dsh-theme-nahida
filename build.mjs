import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, resolve, extname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = dirname(fileURLToPath(import.meta.url));
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const source = readFileSync(resolve(root, 'theme.css'), 'utf8').replace(/\r\n/g, '\n');
const assets = new Map();
const css = source.replace(/url\("(\.\/assets\/[^"]+)"\)/g, (_, file) => {
  const bytes = readFileSync(resolve(root, file));
  const mime = { '.png': 'image/png', '.webp': 'image/webp', '.svg': 'image/svg+xml' }[extname(file)];
  if (!mime) throw new Error(`Unsupported asset: ${file}`);
  assets.set(file, { path: file, bytes: bytes.length, sha256: hash(bytes) });
  return `url("data:${mime};base64,${bytes.toString('base64')}")`;
});
if (/url\(["']?(?:\.\.?\/|https?:)/.test(css)) throw new Error('Theme still has a non-embedded asset');
const light = {}, dark = {};
for (const rule of css.matchAll(/([^{}]*)\{([^{}]*)\}/g)) {
  const target = rule[1].includes('data-ds-dark-theme') ? dark : light;
  for (const token of rule[2].matchAll(/(--dsw-[a-z0-9-]+)\s*:\s*([^;{}]+);/g)) target[token[1]] = token[2].trim();
}
if (Object.keys(light).length < 200 || Object.keys(dark).length !== Object.keys(light).length) throw new Error('Incomplete light/dark token coverage');
const bundle = {
  pluginId: pkg.name, defaultThemeId: 'nahida-maya',
  themes: [{ id: 'nahida', name: '纳西妲', variants: [{
    id: 'nahida-maya', variantKey: 'nahida-maya', themeId: 'nahida', variantId: 'maya',
    name: '纳西妲 · 摩耶之殿', tagline: '让每一个小小的念头，都长成新的可能。',
    recommended: true, css, light, dark,
  }] }],
};
const fragments = readdirSync(resolve(root, 'src/client')).filter(f => f.endsWith('.js')).sort()
  .map(f => readFileSync(resolve(root, 'src/client', f), 'utf8').replace(/\r\n/g, '\n')).join('\n');
const client = `/* ${pkg.name} ${pkg.version} — generated by build.mjs */\n(function(registry) {\nregistry.load({id:${JSON.stringify(pkg.name)},factory(require) {\nconst React = require("react");\nconst THEME_BUNDLE = ${JSON.stringify(bundle)};\n${fragments}\nreturn {inject:['slots','locale'],apply};\n}});\n})(window.__ModuleLoader__);\n`;
mkdirSync(resolve(root, 'dist'), { recursive: true });
writeFileSync(resolve(root, 'dist/client.js'), client);
writeFileSync(resolve(root, 'dist/manifest.json'), JSON.stringify({
  name: pkg.name, version: pkg.version, defaultThemeId: bundle.defaultThemeId,
  themes: ['nahida-maya'], colorSchemes: ['light', 'dark'],
  tokens: { light: Object.keys(light).length, dark: Object.keys(dark).length },
  assets: [...assets.values()], sourceSha256: hash(source), clientSha256: hash(client),
  clientBytes: Buffer.byteLength(client),
  sources: readdirSync(resolve(root, 'src/client')).sort().map(f => relative(root, resolve(root, 'src/client', f)).replaceAll('\\', '/')),
}, null, 2) + '\n');
console.log(`${pkg.name}@${pkg.version}: one theme, ${assets.size} embedded assets, ${Buffer.byteLength(client)} bytes, sha256 ${hash(client)}`);
